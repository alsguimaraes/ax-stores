	<h1>Refund Policy</h1>
	<h2>Returns</h2>
	<p>
		Our policy lasts 30 days. If 30 days have gone by since your purchase, unfortunately we can't offer you a
		refund or exchange.
	</p>
	<p>To be eligible for a return, your item must be:</p>
	<ul>
		<li>Unused and in the same condition that you received it</li>
		<li>In its original packaging</li>
	</ul>
	<p>
		Gift cards are non-returnable. To complete your return, we require a receipt or proof of purchase. Please do
		not send your purchase back to the manufacturer.
	</p>
	<p>There are certain situations where only partial refunds are granted:</p>
	<ul>
		<li>Any item not in its original condition, damaged, or missing parts for reasons not due to our error</li>
		<li>Any item returned more than 30 days after delivery</li>
	</ul>
	<h2>Refunds</h2>
	<p>
		Once your return is received and inspected, we'll email you to confirm we've received your returned item and
		let you know whether your refund has been approved or rejected. If approved, your refund will be processed
		and a credit will automatically be applied to your original method of payment within a certain number of
		days.
	</p>
	<h2>Late or Missing Refunds</h2>
	<p>If you haven't received a refund yet:</p>
	<ul>
		<li>Check your bank account again</li>
		<li>Contact your credit card company - it may take some time before your refund is officially posted</li>
		<li>Contact your bank - there is often some processing time before a refund is posted</li>
	</ul>
	<p>If you've done all of this and still haven't received your refund, please <a href="/contact">contact us</a>.</p>
	<h2>Sale Items</h2>
	<p>Only regular priced items may be refunded - unfortunately, sale items cannot be refunded.</p>
	<h2>Exchanges</h2>
	<p>
		We only replace items if they are defective or damaged. If you need to exchange an item for the same item,
		<a href="/contact">contact us</a> and mail your item to:
	</p>
	<p>16532 Turquoise Trl, Weston, FL 33331, United States</p>
