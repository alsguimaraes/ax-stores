	<h1>Shipping Policy</h1>
	<p>
		Our goal is to offer you the best shipping options no matter where you live. Every item is custom printed
		after your order is placed, so delivery time is made up of two parts: processing and shipping.
	</p>
	<h2>Processing Time</h2>
	<p>
		We aim to prepare most orders within 24 hours, with the exception of beachwear, throw pillows, shorts, and
		leggings, which take about 2-7 business days to fulfill. Shipping time is added on top of processing time -
		speed and price depend on the product type and destination.
	</p>
	<h2>Shipping Times</h2>
	<ul>
		<li>United States Standard: 3-14 business days</li>
		<li>United States First Class with Tracking: 3-7 business days</li>
		<li>United States Priority: 2-3 business days</li>
		<li>United States 1-Day Shipping: 1-day UPS Saver</li>
		<li>European Union: 5-12 business days</li>
		<li>European Union Priority: 3-7 business days</li>
		<li>Rest of the world: 7-20 business days</li>
	</ul>
	<p>Times above are estimates provided by the postal carrier - we can't guarantee they'll be met.</p>
	<h2>All Sales Are Final</h2>
	<p>
		Every order is custom made for each customer, so we don't accept returns or replacements if you ordered the
		wrong size - please check the sizing chart on each product page and <a href="/contact">contact us</a> with
		any questions before ordering.
	</p>
	<p>
		Once you've clicked "Checkout", it's not possible to edit or cancel your order. If you need to change
		something, like your shipping address, <a href="/contact">contact us</a> as soon as possible - we can't
		guarantee we'll be able to make the change, but we'll do our best on a case-by-case basis.
	</p>
	<p>
		For some products, we work with a third-party print fulfillment partner. If carrier tracking shows a package
		was delivered, any lost-shipment claim must be filed with the carrier directly - we're unable to offer
		refunds or reshipments in that case.
	</p>
	<h2>International Shipping</h2>
	<p>
		Shipments outside the US may incur customs fees, duties, or VAT depending on the destination country - these
		are the customer's responsibility. We're not responsible for these charges or for packages held by
		international customs agencies; check with your local customs office for their procedures and potential
		charges.
	</p>
	<p>
		If a package is returned to us because it wasn't picked up, we can't refund the original shipping charge. For
		custom orders, <a href="/contact">contact us</a> immediately to arrange reshipping, since custom orders are
		final sale. As with domestic orders, we're not responsible for extra fees caused by an incorrect shipping
		address.
	</p>
	<h2>Separate Shipments</h2>
	<p>
		Some products ship separately because they're packaged differently - posters, for example, ship in durable
		tubes that other items, like canvases, won't fit in.
	</p>
	<h2>Damaged Items</h2>
	<p>
		If your item arrives damaged, <a href="/contact">get in touch with us</a> within a week. We review
		replacement or return requests for products that are damaged or have a print error.
	</p>
	<h2>"Lost in Transit" Orders</h2>
	<p>
		If your order hasn't arrived, let us know. First, double check your shipping confirmation for the correct
		address - if it was entered incorrectly, we're happy to send a replacement, but at your cost. If the address
		was correct, <a href="/contact">contact us</a> with your order number and we'll look into it.
	</p>
	<h2>More Information</h2>
	<p>
		Browse common questions in our <a href="/help">Help Center</a>, or <a href="/contact">contact us</a> with
		anything else.
	</p>
