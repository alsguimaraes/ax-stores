	<h1>Privacy Policy</h1>
	<p>Last updated: August 2026</p>
	<p>
		This Privacy Policy describes how xpgifts ("we", "us") collects, uses, and shares information when you visit
		or make a purchase from www.xpgifts.com (the "Site").
	</p>
	<h2>Personal Information We Collect</h2>
	<p>
		When you visit the Site, we automatically collect certain information about your device, including your web
		browser, IP address, time zone, and some of the cookies installed on your device. As you browse the Site, we
		also collect information about the pages or products you view, what site or search terms referred you here,
		and how you interact with the Site. We refer to this as "Device Information", collected using:
	</p>
	<ul>
		<li>
			<strong>Cookies</strong> - data files placed on your device, often including an anonymous unique
			identifier. Learn more at
			<a href="http://www.allaboutcookies.org" target="_blank" rel="noopener noreferrer">allaboutcookies.org</a>.
		</li>
		<li>
			<strong>Log files</strong> - track actions on the Site and collect your IP address, browser type,
			internet service provider, referring/exit pages, and date/time stamps.
		</li>
		<li><strong>Web beacons, tags, and pixels</strong> - electronic files used to record how you browse the Site.</li>
	</ul>
	<p>
		When you place or attempt to place an order, we also collect your name, billing and shipping address, payment
		information, email address, and phone number ("Order Information"). Together, Device Information and Order
		Information make up "Personal Information".
	</p>
