	<h1>Shipping Policy</h1>
	<h2>Processing Time</h2>
	<p>
		Because most items are personalized and made to order, please allow 2-4 business days for your order to be
		processed before it ships.
	</p>
	<h2>Shipping Times</h2>
	<ul>
		<li>Domestic (US): 5-9 business days after processing</li>
		<li>International: 2-3 weeks after processing, depending on destination</li>
	</ul>
	<h2>Shipping Costs</h2>
	<p>Shipping costs are calculated at checkout based on your location and order weight.</p>
	<h2>Order Tracking</h2>
	<p>
		Once your order ships, you'll receive a confirmation email with tracking information. You can also check the
		latest status from <a href="/my-account/orders">My Account → Orders</a>.
	</p>
